function formatSearchResultsBlock(results: LegalSearchResult[]): string {
  const direct = results.filter((result) => result.relevance_status === "direct");
  const related = results.filter((result) => result.relevance_status === "related");

  if (direct.length === 0 && related.length === 0) {
    return `ОФИЦИАЛЬНЫЕ ИСТОЧНИКИ, НАЙДЕННЫЕ СЕРВЕРОМ:
Прямой текст нормативного акта не найден в официальных источниках. Не указывай URL, которых нет в этом списке.`;
  }

  const formatItems = (items: LegalSearchResult[], label: string) =>
    items
      .map(
        (result, index) => `${index + 1}. [${label}] title: ${result.title}
   url: ${result.url}
   source_domain: ${result.source_domain}
   source_type: ${result.source_type ?? "legal_act"}
   relevance_status: ${result.relevance_status}
   matched_act_name: ${result.matched_act_name ?? "не определено"}
   content: ${result.content.slice(0, 500)}`,
      )
      .join("\n\n");

  const blocks = [
    direct.length > 0 ? `ПРЯМЫЕ ИСТОЧНИКИ:\n${formatItems(direct, "direct")}` : "",
    related.length > 0
      ? `СВЯЗАННЫЕ МАТЕРИАЛЫ (только дополнительный контекст, не подтверждают статью):\n${formatItems(related, "related")}`
      : "",
  ].filter(Boolean);

  return `ОФИЦИАЛЬНЫЕ ИСТОЧНИКИ, НАЙДЕННЫЕ СЕРВЕРОМ:
${blocks.join("\n\n")}`;
}

/**
 * Семантический контекст из локального корпуса НПА. Передаются только
 * act_name, article_number и текст статьи: векторы и параметры эмбеддингов в
 * промпт не попадают. Блок сопровождается правилами, потому что близость по
 * смыслу не подтверждает ни официальность источника, ни конкретную статью.
 */
function formatRetrievalContextBlock(
  records: LegalEmbeddingSearchResult[],
): string {
  if (records.length === 0) {
    return "";
  }

  const items = records
    .map(
      (record, index) => `${index + 1}. act_name: ${record.act_name}
   article_number: ${record.article_number}
   text: ${record.chunk_text}`,
    )
    .join("\n\n");

  return `СЕМАНТИЧЕСКИЙ КОНТЕКСТ ИЗ ЛОКАЛЬНОГО КОРПУСА НПА (только контекст, не подтверждение):
${items}

Правила использования этого блока:
1. Это подбор по смысловой близости, а не результат официальной проверки источника.
2. Он не подтверждает ни официальность источника, ни конкретную статью.
3. Он не заменяет direct-источник из серверного списка выше и не даёт права указывать URL.
4. Сам по себе он не делает утверждение подтверждённым: серверные признаки подтверждения проверяются отдельно.
5. Если статья есть только в этом блоке, но её нет в direct-источниках, пиши: «Точная статья требует проверки в официальной базе».`;
}

